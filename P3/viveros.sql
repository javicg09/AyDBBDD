\echo '--- D1: después ---'
SELECT id_pedido, importe FROM pedido WHERE id_pedido = 1;
SELECT * FROM bonificacion WHERE id_cliente = 1 AND anio = 2025 AND mes = 2;

-- D2. Borrar un pedido → CASCADE en sus líneas y la bonificación baja de tramo
DELETE FROM pedido WHERE id_pedido = 2;
\echo '--- D2: bonificación de febrero tras borrar el pedido 2 (pasa del 5% al 2%) ---'
