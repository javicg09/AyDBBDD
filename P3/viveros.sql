DROP DATABASE IF EXISTS viveros;
CREATE DATABASE viveros;
\c viveros

-- Necesaria para la restricción EXCLUDE (un empleado no trabaja a la vez en dos viveros)
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- =====================================================================
-- 1. TABLAS
-- =====================================================================

-- ---------- VIVERO ---------------------------------------------------
CREATE TABLE vivero (
    id_vivero   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100)  NOT NULL UNIQUE CHECK (btrim(nombre) <> ''),
    latitud     NUMERIC(9,6)  NOT NULL CHECK (latitud  BETWEEN -90  AND 90),
    longitud    NUMERIC(9,6)  NOT NULL CHECK (longitud BETWEEN -180 AND 180)
);

-- ---------- ZONA (entidad débil de VIVERO) ---------------------------
CREATE TABLE zona (
    id_vivero   INTEGER       NOT NULL,
    id_zona     SMALLINT      NOT NULL CHECK (id_zona > 0),
    nombre      VARCHAR(50)   NOT NULL CHECK (btrim(nombre) <> ''),
    latitud     NUMERIC(9,6)  NOT NULL CHECK (latitud  BETWEEN -90  AND 90),
    longitud    NUMERIC(9,6)  NOT NULL CHECK (longitud BETWEEN -180 AND 180),
    PRIMARY KEY (id_vivero, id_zona),
    UNIQUE (id_vivero, nombre),                      -- no hay dos "Almacén" en el mismo vivero
    FOREIGN KEY (id_vivero) REFERENCES vivero (id_vivero)
        ON DELETE CASCADE ON UPDATE CASCADE          -- débil: muere con su vivero
);

-- ---------- PRODUCTO -------------------------------------------------
CREATE TABLE producto (
    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100)  NOT NULL CHECK (btrim(nombre) <> ''),
    tipo        VARCHAR(15)   NOT NULL CHECK (tipo IN ('Planta', 'Jardinería', 'Decoración')),
    precio      NUMERIC(10,2) NOT NULL CHECK (precio >= 0)
);

-- ---------- STOCK (Zona N:M Producto) --------------------------------
CREATE TABLE stock (
    id_vivero   INTEGER  NOT NULL,
    id_zona     SMALLINT NOT NULL,
    id_producto INTEGER  NOT NULL,
    cantidad    INTEGER  NOT NULL DEFAULT 0 CHECK (cantidad >= 0),
    PRIMARY KEY (id_vivero, id_zona, id_producto),
    FOREIGN KEY (id_vivero, id_zona) REFERENCES zona (id_vivero, id_zona)
        ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (id_producto) REFERENCES producto (id_producto)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- ---------- EMPLEADO -------------------------------------------------
CREATE TABLE empleado (
    id_empleado INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dni         CHAR(9)       NOT NULL UNIQUE CHECK (dni ~ '^[0-9]{8}[A-Z]$'),
    nombre      VARCHAR(100)  NOT NULL CHECK (btrim(nombre) <> '')
);

-- ---------- TAREA / PUESTO -------------------------------------------
CREATE TABLE tarea (
    id_tarea    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion VARCHAR(100)  NOT NULL UNIQUE CHECK (btrim(descripcion) <> '')
);

-- ---------- DESEMPEÑO (ternaria Empleado – Zona – Tarea) --------------
-- El empleado solo se relaciona con la zona; el vivero se conoce porque
-- forma parte de la clave de la zona.
CREATE TABLE desempeno (
    id_empleado   INTEGER  NOT NULL,
    id_vivero     INTEGER  NOT NULL,
    id_zona       SMALLINT NOT NULL,
    id_tarea      INTEGER  NOT NULL,
    fecha_inicio  DATE     NOT NULL,
    fecha_fin     DATE,                              -- NULL = puesto actual
    productividad NUMERIC(5,2) CHECK (productividad BETWEEN 0 AND 100),  -- NULL = aún sin evaluar
    PRIMARY KEY (id_empleado, id_vivero, id_zona, id_tarea, fecha_inicio),
    CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
    -- Nunca dos destinos a la vez: no puede haber periodos solapados
    -- del mismo empleado en viveros DISTINTOS (sí varias tareas en el mismo)
    EXCLUDE USING gist (
        id_empleado WITH =,
        id_vivero   WITH <>,
        daterange(fecha_inicio, fecha_fin, '[]') WITH &&
    ),
    FOREIGN KEY (id_empleado) REFERENCES empleado (id_empleado)
        ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (id_vivero, id_zona) REFERENCES zona (id_vivero, id_zona)
        ON DELETE RESTRICT ON UPDATE CASCADE,        -- no se borra una zona (ni su vivero) con histórico de personal
    FOREIGN KEY (id_tarea) REFERENCES tarea (id_tarea)
        ON DELETE RESTRICT ON UPDATE CASCADE
);

-- ---------- CLIENTE (Tajinaste Plus) ---------------------------------
CREATE TABLE cliente (
    id_cliente    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(100) NOT NULL CHECK (btrim(nombre) <> ''),
    email         VARCHAR(150) UNIQUE CHECK (email ~* '^[^@\s]+@[^@\s]+\.[a-z]{2,}$'),  -- opcional
    fecha_ingreso DATE         NOT NULL DEFAULT CURRENT_DATE
);

-- ---------- PEDIDO ---------------------------------------------------
CREATE TABLE pedido (
    id_pedido   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente  INTEGER       NOT NULL,
    id_empleado INTEGER       NOT NULL DEFAULT 0,    -- 0 = "Sin asignar"
    fecha       DATE          NOT NULL DEFAULT CURRENT_DATE,
    importe     NUMERIC(12,2) NOT NULL DEFAULT 0,    -- DERIVADO: suma de subtotales (trigger)
    FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente)
        ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (id_empleado) REFERENCES empleado (id_empleado)
        ON DELETE SET DEFAULT ON UPDATE CASCADE      -- si se va el responsable, pasa a "Sin asignar"
);

-- ---------- LÍNEA DE PEDIDO (relación Contiene) ----------------------
CREATE TABLE linea_pedido (
    id_pedido       INTEGER       NOT NULL,
    id_producto     INTEGER       NOT NULL,
    cantidad        INTEGER       NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10,2) NOT NULL CHECK (precio_unitario >= 0),  -- si no se indica, se copia del producto
    subtotal        NUMERIC(12,2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED,  -- DERIVADO
    PRIMARY KEY (id_pedido, id_producto),
    FOREIGN KEY (id_pedido) REFERENCES pedido (id_pedido)
        ON DELETE CASCADE ON UPDATE CASCADE,
    FOREIGN KEY (id_producto) REFERENCES producto (id_producto)
        ON DELETE RESTRICT ON UPDATE CASCADE         -- no se borran productos ya vendidos
);

-- ---------- BONIFICACIÓN (entidad débil de CLIENTE) ------------------
CREATE TABLE bonificacion (
    id_cliente      INTEGER       NOT NULL,
    anio            SMALLINT      NOT NULL CHECK (anio BETWEEN 2000 AND 2100),
    mes             SMALLINT      NOT NULL CHECK (mes BETWEEN 1 AND 12),
    volumen_compras NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (volumen_compras >= 0),  -- DERIVADO (trigger)
    porcentaje      NUMERIC(4,2)  GENERATED ALWAYS AS (                              -- DERIVADO
        CASE WHEN volumen_compras >= 1000 THEN 10
             WHEN volumen_compras >=  500 THEN  5
             WHEN volumen_compras >=  100 THEN  2
             ELSE 0 END) STORED,
    importe         NUMERIC(10,2) GENERATED ALWAYS AS (                              -- DERIVADO
        ROUND(volumen_compras *
              CASE WHEN volumen_compras >= 1000 THEN 10
                   WHEN volumen_compras >=  500 THEN  5
                   WHEN volumen_compras >=  100 THEN  2
                   ELSE 0 END / 100, 2)) STORED,
    PRIMARY KEY (id_cliente, anio, mes),
    FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente)
        ON DELETE CASCADE ON UPDATE CASCADE
);

-- =====================================================================
-- 2. TRIGGERS (atributos derivados y restricciones semánticas)
-- =====================================================================

-- Precio unitario por defecto = precio actual del producto
CREATE FUNCTION fn_precio_linea() RETURNS trigger AS $$
BEGIN
    IF NEW.precio_unitario IS NULL THEN
        SELECT precio INTO NEW.precio_unitario
        FROM producto WHERE id_producto = NEW.id_producto;
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_precio_linea
BEFORE INSERT ON linea_pedido
FOR EACH ROW EXECUTE FUNCTION fn_precio_linea();

-- PEDIDO: el importe siempre se recalcula (no puede escribirse a mano)
--         y la fecha no puede ser anterior al ingreso del cliente (R5).
CREATE FUNCTION fn_pedido_before() RETURNS trigger AS $$
BEGIN
    IF NEW.fecha < (SELECT fecha_ingreso FROM cliente WHERE id_cliente = NEW.id_cliente) THEN
        RAISE EXCEPTION 'El pedido (%) es anterior al ingreso del cliente % en Tajinaste Plus',
                        NEW.fecha, NEW.id_cliente;
    END IF;
    NEW.importe := COALESCE((SELECT SUM(subtotal) FROM linea_pedido
                             WHERE id_pedido = NEW.id_pedido), 0);
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_pedido_before
BEFORE INSERT OR UPDATE ON pedido
FOR EACH ROW EXECUTE FUNCTION fn_pedido_before();

-- Cuando cambian las líneas, se fuerza el recálculo del importe del pedido
CREATE FUNCTION fn_linea_after() RETURNS trigger AS $$
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        UPDATE pedido SET importe = importe WHERE id_pedido = OLD.id_pedido;
    END IF;
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        UPDATE pedido SET importe = importe WHERE id_pedido = NEW.id_pedido;
    END IF;
    RETURN NULL;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_linea_after
AFTER INSERT OR UPDATE OR DELETE ON linea_pedido
FOR EACH ROW EXECUTE FUNCTION fn_linea_after();

-- BONIFICACIÓN: volumen_compras = suma de importes del cliente en ese mes
CREATE FUNCTION fn_recalcular_bonificacion(p_cliente INTEGER, p_fecha DATE)
RETURNS void AS $$
DECLARE
    v_num   INTEGER;
    v_total NUMERIC(12,2);
BEGIN
    SELECT COUNT(*), COALESCE(SUM(importe), 0) INTO v_num, v_total
    FROM pedido
    WHERE id_cliente = p_cliente
      AND date_trunc('month', fecha) = date_trunc('month', p_fecha);

    IF v_num = 0 THEN
        DELETE FROM bonificacion
        WHERE id_cliente = p_cliente
          AND anio = EXTRACT(YEAR  FROM p_fecha)
          AND mes  = EXTRACT(MONTH FROM p_fecha);
    ELSE
        INSERT INTO bonificacion (id_cliente, anio, mes, volumen_compras)
        VALUES (p_cliente, EXTRACT(YEAR FROM p_fecha), EXTRACT(MONTH FROM p_fecha), v_total)
        ON CONFLICT (id_cliente, anio, mes)
        DO UPDATE SET volumen_compras = EXCLUDED.volumen_compras;
    END IF;
END $$ LANGUAGE plpgsql;

CREATE FUNCTION fn_pedido_after() RETURNS trigger AS $$
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        PERFORM fn_recalcular_bonificacion(OLD.id_cliente, OLD.fecha);
    END IF;
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        PERFORM fn_recalcular_bonificacion(NEW.id_cliente, NEW.fecha);
    END IF;
    RETURN NULL;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_pedido_after
AFTER INSERT OR UPDATE OR DELETE ON pedido
FOR EACH ROW EXECUTE FUNCTION fn_pedido_after();

